package com.example

object TermPaperMathBank {

  fun generateMathQuestion(grade: String, term: Int, paperIdx: Int, qNum: Int): MockExamQuestion {
    val topic = when (qNum) {
      in 1..10 -> "වීජ ගණිතය සහ සාධක"
      in 11..20 -> "මූල්‍ය ගණිතය සහ පොලිය"
      in 21..35 -> "ජ්‍යාමිතිය, කෝණ සහ වෘත්ත ප්‍රමේය"
      in 36..42 -> "ත්‍රිකෝණමිතිය සහ උස-දුර"
      in 43..48 -> "සංඛ්‍යානය, මාතය සහ මධ්‍යනය"
      in 49..54 -> "සම්භාවිතාව සහ කුලක"
      else -> "ශ්‍රේඪි, න්‍යාස සහ අසමානතා"
    }

    val p = paperIdx
    val (qText, rawOpts, explanation) = when (qNum) {
      1 -> {
        val a = p + 2
        Triple(
          "x² - ${a*a} හි සාධක වෙන් කළ විට ලැබෙන වීජීය ප්‍රකාශනය කුමක්ද?",
          listOf("(x - $a)(x + $a)", "(x - $a)²", "(x + $a)²", "(x - ${a*2})(x + 2)"),
          "a² - b² = (a - b)(a + b) වර්ග දෙකක අන්තරය සූත්‍රය අනුව: x² - $a² = (x - $a)(x + $a) වේ."
        )
      }
      2 -> {
        val m = (p % 6) + 2
        val n = (p % 4) + 3
        val b = m + n
        val c = m * n
        Triple(
          "x² + ${b}x + $c ප්‍රකාශනයේ සාධක යුගලය වන්නේ,",
          listOf("(x + $m)(x + $n)", "(x - $m)(x - $n)", "(x + ${m+1})(x + ${n-1})", "(x + 1)(x + $c)"),
          "ගුණිතය $c ද එකතුව $b ද වන සංඛ්‍යා යුගලය $m සහ $n බැවින්: (x + $m)(x + $n) වේ."
        )
      }
      3 -> {
        val r1 = (p % 5) + 1
        val r2 = (p % 4) + 5
        Triple(
          "x² - ${r1+r2}x + ${r1*r2} = 0 වර්ගජ සමීකරණයේ විසඳුම් (මූල) යුගලය කුමක්ද?",
          listOf("x = $r1 හෝ x = $r2", "x = -$r1 හෝ x = -$r2", "x = ${r1+2} හෝ x = ${r2-2}", "x = 0 හෝ x = ${r1*r2}"),
          "(x - $r1)(x - $r2) = 0 බැවින්: x = $r1 හෝ x = $r2 වේ."
        )
      }
      4 -> {
        val xVal = p + 4
        val yVal = (p % 5) + 2
        val s1 = xVal + yVal
        val d1 = xVal - yVal
        Triple(
          "x + y = $s1 සහ x - y = $d1 සමගාමී සමීකරණ යුගලයේ විසඳුම වන්නේ,",
          listOf("x = $xVal, y = $yVal", "x = $yVal, y = $xVal", "x = ${xVal+1}, y = ${yVal-1}", "x = ${xVal*2}, y = $yVal"),
          "සමීකරණ දෙක එකතු කළ විට: 2x = ${s1+d1} => x = $xVal. ආදේශයෙන් y = $yVal."
        )
      }
      5 -> {
        val k = (p % 7) + 3
        Triple(
          "(x² - ${k*k}) / (x - $k) වීජීය භාගය සරල කළ විට අවසාන අගය:",
          listOf("x + $k", "x - $k", "x + ${k*2}", "(x + $k)²"),
          "(x - $k)(x + $k) / (x - $k) හි (x - $k) පොදු සාධකය කැපී ගොස් x + $k ඉතිරි වේ."
        )
      }
      6 -> {
        val bBase = (p % 3) + 2
        val mPow = (p % 4) + 3
        val nPow = (p % 3) + 2
        Triple(
          "$bBase^$mPow × $bBase^$nPow / $bBase^${mPow-1} හි අගය දර්ශක ආකාරයෙන් ලියූ විට:",
          listOf("$bBase^${nPow+1}", "$bBase^${mPow+nPow}", "$bBase^$nPow", "$bBase^${mPow-nPow}"),
          "පාද සමාන ගුණිතයේදී දර්ශක එකතු වන අතර බෙදීමේදී අඩු වේ: $bBase^($mPow + $nPow - ${mPow-1}) = $bBase^${nPow+1}."
        )
      }
      7 -> {
        val bLog = (p % 3) + 2
        val pLog = (p % 3) + 2
        val valLog = Math.pow(bLog.toDouble(), pLog.toDouble()).toInt()
        Triple(
          "log_$bLog($valLog) = $pLog ප්‍රකාශනය දර්ශක ආකාරයෙන් දැක්වූ විට:",
          listOf("$bLog^$pLog = $valLog", "$pLog^$bLog = $valLog", "$valLog^$pLog = $bLog", "$bLog × $pLog = $valLog"),
          "ලඝුගණක නිර්වචනය අනුව log_a(b) = c නම් a^c = b වේ. එබැවින් $bLog^$pLog = $valLog."
        )
      }
      8 -> {
        val xL = (p % 5) + 2
        val yL = (p % 4) + 3
        Triple(
          "log($xL) + log($yL) ලඝුගණක ප්‍රකාශනය තනි ලඝුගණකයක් ලෙස දැක්වූ විට:",
          listOf("log(${xL * yL})", "log(${xL + yL})", "log(${xL} / ${yL})", "${xL}log(${yL})"),
          "log(A) + log(B) = log(A × B) ලඝු නීතිය අනුව log($xL × $yL) = log(${xL * yL}) වේ."
        )
      }
      9 -> {
        val mult = (p % 5) + 1
        val aP = 3 * mult
        val bP = 4 * mult
        val cP = 5 * mult
        Triple(
          "ඍජුකෝණී ත්‍රිකෝණයක ඍජුකෝණය සාදන පාද $aP cm සහ $bP cm වේ නම් කර්ණයේ දිග:",
          listOf("$cP cm", "${cP + 2} cm", "${aP + bP} cm", "${cP * 2} cm"),
          "පයිතගරස් ප්‍රමේයය අනුව: c² = $aP² + $bP² = ${aP*aP + bP*bP} => c = $cP cm."
        )
      }
      10 -> {
        val m5 = (p % 4) + 1
        val a5 = 5 * m5
        val b5 = 12 * m5
        val c5 = 13 * m5
        Triple(
          "ඍජුකෝණී ත්‍රිකෝණයක කර්ණය $c5 cm ද එක් පාදයක් $a5 cm ද වේ නම් අනෙක් පාදයේ දිග:",
          listOf("$b5 cm", "${b5 + 2} cm", "${c5 - a5} cm", "${b5 - 2} cm"),
          "b² = $c5² - $a5² = ${c5*c5 - a5*a5} => b = $b5 cm වේ."
        )
      }
      11 -> {
        val princ = (p * 5000) + 10000
        val rate = (p % 5) + 6
        val interest = (princ * 2 * rate) / 100
        Triple(
          "රු. $princ ක මුදලක් වාර්ෂික $rate% සුළු පොලී අනුපාතයට වසර 2ක් තැන්පත් කළ විට ලැබෙන මුළු පොලිය:",
          listOf("රු. $interest", "රු. ${interest + 400}", "රු. ${princ + interest}", "රු. ${interest / 2}"),
          "I = (P × T × R) / 100 = ($princ × 2 × $rate) / 100 = රු. $interest වේ."
        )
      }
      12 -> {
        val princ2 = (p * 10000) + 20000
        val tot2 = (princ2 * 1.1 * 1.1).toInt()
        Triple(
          "රු. $princ2 ක ණය මුදලකට වාර්ෂික 10% වැල් පොලී අනුපාතයට වසර 2ක් අවසානයේ ගෙවිය යුතු මුළු මුදල:",
          listOf("රු. $tot2", "රු. ${princ2 + (princ2*2*10)/100}", "රු. ${tot2 + 1000}", "රු. ${tot2 - 800}"),
          "වසර 1 අවසානයේ = රු. ${(princ2*1.1).toInt()}, වසර 2 අවසානයේ = රු. ${(princ2*1.1).toInt()} × 1.1 = රු. $tot2."
        )
      }
      13 -> {
        val aDeg = 40 + (p % 20)
        val bDeg = 60 + (p % 15)
        val cDeg = 180 - aDeg - bDeg
        Triple(
          "ත්‍රිකෝණයක අභ්‍යන්තර කෝණ දෙකක් $aDeg° සහ $bDeg° වේ නම් එහි තුන්වන කෝණයේ අගය:",
          listOf("$cDeg°", "${cDeg + 10}°", "${180 - aDeg}°", "${aDeg + bDeg}°"),
          "ත්‍රිකෝණයක අභ්‍යන්තර කෝණ තුනෙහි එකතුව 180° කි. තුන්වන කෝණය = 180° - ($aDeg° + $bDeg°) = $cDeg°."
        )
      }
      14 -> {
        val eA = 35 + (p % 25)
        val eB = 45 + (p % 20)
        val ext = eA + eB
        Triple(
          "ත්‍රිකෝණයක අභ්‍යන්තර සම්මුඛ කෝණ දෙක $eA° සහ $eB° නම්, පාදයක් දික් කිරීමෙන් සෑදෙන බාහිර කෝණය:",
          listOf("$ext°", "${180 - ext}°", "${ext + 15}°", "${eA + 90}°"),
          "ත්‍රිකෝණයක බාහිර කෝණය අභ්‍යන්තර සම්මුඛ කෝණ දෙකෙහි එකතුවට සමාන වේ: $eA° + $eB° = $ext°."
        )
      }
      15 -> {
        val sA = 50 + (p % 40)
        val sB = 180 - sA
        Triple(
          "සරල රේඛාවක් මත යාබද කෝණ දෙකකින් එකක් $sA° වේ නම් අනෙක් කෝණයේ අගය:",
          listOf("$sB°", "${sB + 10}°", "${90 - sA/2}°", "${360 - sA}°"),
          "සරල රේඛාවක් මත යාබද කෝණවල ඓක්‍යය 180° කි. 180° - $sA° = $sB°."
        )
      }
      16 -> {
        val p1 = 100 + (p % 30)
        val p2 = 120 + (p % 20)
        val p3 = 360 - p1 - p2
        Triple(
          "ලක්ෂ්‍යයක් වටා ඇති කෝණ තුනකින් දෙකක් $p1° සහ $p2° නම් තුන්වන කෝණයේ අගය:",
          listOf("$p3°", "${p3 + 20}°", "${180 - p1}°", "${360 - p2}°"),
          "ලක්ෂ්‍යයක් වටා කෝණවල ඓක්‍යය 360° කි. 360° - ($p1° + $p2°) = $p3°."
        )
      }
      17 -> {
        val altA = 55 + (p % 35)
        Triple(
          "සමාන්තර සරල රේඛා දෙකක් තීර්යක් රේඛාවකින් ඡේදනය වන විට සෑදෙන ඒකාන්තර කෝණ යුගලයකින් එකක් $altA° නම් අනෙක:",
          listOf("$altA°", "${180 - altA}°", "${90 - altA/2}°", "${altA * 2}°"),
          "සමාන්තර රේඛා අතර සෑදෙන Z අකුරේ හැඩති ඒකාන්තර කෝණ එකිනෙකට සමාන වේ."
        )
      }
      18 -> {
        val caseName = when(p % 4) { 0 -> "පා.කෝ.පා (SAS)"; 1 -> "පා.පා.පා (SSS)"; 2 -> "කෝ.කෝ.පා (AAS)"; else -> "කර්ණ.පා (RHS)" }
        Triple(
          "ත්‍රිකෝණ දෙකක අනුරූප අංග සමාන වීම පිළිබඳ $caseName අවස්ථාව යනු,",
          listOf("ත්‍රිකෝණ අංගසම වීමේ නිවැරදි ප්‍රමේයයකි", "සමරූපී වීමේ පමණක් ලක්ෂණයකි", "සමපාද ත්‍රිකෝණවලට පමණක් අදාළ වේ", "කෝණ ඓක්‍ය සූත්‍රයකි"),
          "$caseName යනු ත්‍රිකෝණ දෙකක් එකිනෙකට පූර්ණ ලෙස අංගසම වීමේ පිළිගත් ජ්‍යාමිතික අවස්ථාවකි."
        )
      }
      19 -> {
        val bc = (p * 2) + 12
        val de = bc / 2
        Triple(
